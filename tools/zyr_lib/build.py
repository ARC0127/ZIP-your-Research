MODULE_RE = re.compile(r"^\d{2}_.+\.md$")
SKILL_ID_RE = re.compile(r"S(\d+)")
SKILL_MAP_ORDER = [
    "research_core",
    "experiments",
    "reproducibility",
    "paper_ops",
    "research_writing_integrated",
    "figure_design_integrated",
    "s340_integrated",
    "reproducibility_integrated",
    "composite",
]
Renderer = Callable[[Path, dict[str, Any], list[dict[str, Any]]], str]


def _module_files(root: Path, relative_dir: str) -> list[Path]:
    directory = resolve_repo_path(root, relative_dir, "module directory")
    modules = sorted(
        path
        for path in directory.iterdir()
        if path.is_file()
        and MODULE_RE.fullmatch(path.name)
        and not path.name.startswith("99_")
    )
    if not modules:
        raise RepositoryContractError(f"No source modules found in {relative_dir}")
    return modules


def render_writing_engine(
    root: Path, manifest: dict[str, Any], _entries: list[dict[str, Any]]
) -> str:
    """Render the authoritative writing master."""
    version = str(manifest["version"])
    parts = [
        f"# MASTER v{version} (Writing Engine)\n",
        "> This file is generated by `python tools/zyr.py build`.\n",
        (
            "> **Component lineage:** the preserved writing modules originate from the "
            "v1.3.2-compatible prompt line; the active suite and this entrypoint are "
            f"v{version}.\n"
        ),
        (
            f"> **v{version} binding addendum:** Any visible writing task in ZYR must call "
            f"`writing_engine`. In the v{version} stack, `writing_engine` is backed by "
            "`ext/src/rpws/` (Research-Paper-Writing-Skills) and must use the integrated "
            "wrappers `S601`/`S602`/`S603`/`S604` together with `S640` as the global "
            "writing and logic gate.\n"
        ),
        (
            "> **Execution rules:** `boot/11_COMPLETION_FIRST_ANTI_SHORTCUT_v1.5.md` "
            "applies after lock activation.\n\n---\n"
        ),
    ]
    parts.insert(1, engine_addendum("writing_engine"))
    for path in _module_files(root, "skills/writing_engine/modules"):
        parts.append(path.read_text(encoding="utf-8").rstrip())
        parts.append("\n\n---\n")
    return "\n".join(parts).rstrip() + "\n"


